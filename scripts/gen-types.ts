/**
 * Generates src/data/database.types.ts from the migrations (applied to an embedded Postgres),
 * so the TypeScript types always match the schema without needing Docker or the Supabase CLI.
 * Run with: pnpm types
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createDb } from '../tests/db/harness'

const SCALAR: Record<string, string> = {
  uuid: 'string', text: 'string', varchar: 'string', date: 'string', time: 'string',
  timestamptz: 'string', timestamp: 'string', bool: 'boolean', boolean: 'boolean',
  int2: 'number', int4: 'number', int8: 'number', integer: 'number', smallint: 'number',
  bigint: 'number', numeric: 'number', jsonb: 'Json', json: 'Json', void: 'undefined',
}

const SQL_NAMES: Record<string, string> = {
  'timestamp with time zone': 'timestamptz',
  'timestamp without time zone': 'timestamp',
  'time without time zone': 'time',
  'character varying': 'varchar',
  'double precision': 'numeric',
}

function tsType(udt: string, enums: Set<string>): string {
  udt = SQL_NAMES[udt.replace(/\[\]$/, '')] ? `${SQL_NAMES[udt.replace(/\[\]$/, '')]}${udt.endsWith('[]') ? '[]' : ''}` : udt
  const base = udt.replace(/^_/, '').replace(/\[\]$/, '')
  const isArray = udt.startsWith('_') || udt.endsWith('[]')
  const clean = base.replace(/^public\./, '')
  const t = enums.has(clean) ? `Database['public']['Enums']['${clean}']` : (SCALAR[clean] ?? 'unknown')
  return isArray ? `${t}[]` : t
}

const db = await createDb()
const q = async <T extends object>(sql: string) => (await db.pg.query<T>(sql)).rows

const enumRows = await q<{ name: string; label: string }>(
  `select t.typname as name, e.enumlabel as label from pg_type t
   join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' order by t.typname, e.enumsortorder`,
)
const enums = new Map<string, string[]>()
for (const r of enumRows) enums.set(r.name, [...(enums.get(r.name) ?? []), r.label])
const enumNames = new Set(enums.keys())

const cols = await q<{ table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null; table_type: string }>(
  `select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, t.table_type
   from information_schema.columns c join information_schema.tables t
     on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public' order by c.table_name, c.ordinal_position`,
)
const relations = new Map<string, typeof cols>()
for (const c of cols) relations.set(c.table_name, [...(relations.get(c.table_name) ?? []), c])

const fns = await q<{ name: string; args: string; result: string }>(
  `select p.proname as name, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
   from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f' order by p.proname`,
)

const out: string[] = []
out.push('// GENERATED by scripts/gen-types.ts from supabase/migrations. Do not edit by hand.')
out.push('// Regenerate with: pnpm types\n')
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n')
out.push('export type Database = {\n  public: {')

for (const kind of ['BASE TABLE', 'VIEW'] as const) {
  out.push(`    ${kind === 'VIEW' ? 'Views' : 'Tables'}: {`)
  for (const [name, columns] of relations) {
    if (columns[0]!.table_type !== kind) continue
    const row = columns.map((c) => `${c.column_name}: ${tsType(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`)
    const optional = (c: (typeof columns)[number]) => c.is_nullable === 'YES' || c.column_default !== null
    const insert = columns.map((c) => `${c.column_name}${optional(c) ? '?' : ''}: ${tsType(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`)
    const update = columns.map((c) => `${c.column_name}?: ${tsType(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`)
    out.push(`      ${name}: {`)
    out.push(`        Row: { ${row.join('; ')} }`)
    if (kind === 'BASE TABLE') {
      out.push(`        Insert: { ${insert.join('; ')} }`)
      out.push(`        Update: { ${update.join('; ')} }`)
    }
    out.push('        Relationships: []')
    out.push('      }')
  }
  out.push('    }')
}

out.push('    Functions: {')
for (const f of fns) {
  if (f.result === 'trigger' || ['is_household_member', 'person_in_my_household', 'require_household', 'bolivia_today'].includes(f.name)) continue
  const args = f.args.trim()
    ? f.args.split(/,\s*(?![^()]*\))/).map((a) => {
        const m = /^(?:IN\s+)?(\w+)\s+(.+?)(\s+DEFAULT\s+.*)?$/i.exec(a.trim())
        if (!m) throw new Error(`Cannot parse argument "${a}" of ${f.name}`)
        return `${m[1]}${m[3] ? '?' : ''}: ${tsType(m[2]!, enumNames)}`
      })
    : []
  const setof = /^SETOF\s+(\S+)/i.exec(f.result)
  const resultName = f.result.replace('public.', '')
  const ret = setof
    ? `Database['public']['Tables']['${setof[1]!.replace('public.', '')}']['Row'][]`
    : relations.has(resultName)
      ? `Database['public']['Tables']['${resultName}']['Row']`
      : tsType(f.result, enumNames)
  out.push(`      ${f.name}: { Args: ${args.length ? `{ ${args.join('; ')} }` : 'Record<PropertyKey, never>'}; Returns: ${ret} }`)
}
out.push('    }')

out.push('    Enums: {')
for (const [name, labels] of enums) out.push(`      ${name}: ${labels.map((l) => `'${l}'`).join(' | ')}`)
out.push('    }')
out.push('    CompositeTypes: Record<string, never>')
out.push('  }')
out.push('}\n')
out.push("export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row']")
out.push("export type Views<T extends keyof Database['public']['Views']> = Database['public']['Views'][T]['Row']")
out.push("export type Enums<T extends keyof Database['public']['Enums']> = Database['public']['Enums'][T]")

writeFileSync(join(import.meta.dirname, '..', 'src', 'data', 'database.types.ts'), out.join('\n') + '\n')
await db.close()
console.log(`Generated types for ${relations.size} relations, ${fns.length} functions, ${enums.size} enums`)
