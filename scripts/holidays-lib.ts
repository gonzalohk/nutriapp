import Holidays from 'date-holidays'

export interface Holiday {
  date: string // YYYY-MM-DD
  name: string
}

/**
 * Bolivian public holidays for a year, computed by rule (movable ones such as Carnival, Good Friday
 * and Corpus Christi move every year; a holiday on a Sunday may be shifted). Only `public` holidays
 * block deliveries; `observance` days such as Mother's Day or Maundy Thursday do not.
 */
export function bolivianPublicHolidays(year: number): Holiday[] {
  const calendar = new Holidays('BO')
  const byDate = new Map<string, string>()
  for (const h of calendar.getHolidays(year)) {
    if (h.type !== 'public') continue
    const date = h.date.slice(0, 10)
    if (!byDate.has(date)) byDate.set(date, h.name)
  }
  return [...byDate.entries()].sort(([a], [b]) => (a < b ? -1 : 1)).map(([date, name]) => ({ date, name }))
}

const quote = (s: string) => `'${s.replaceAll("'", "''")}'`

/** SQL for an idempotent data migration covering `fromYear..toYear` (inclusive). */
export function buildHolidayMigration(fromYear: number, toYear: number): string {
  const rows: string[] = []
  for (let y = fromYear; y <= toYear; y++) {
    for (const h of bolivianPublicHolidays(y)) rows.push(`  ('BO', ${quote(h.date)}, ${quote(h.name)})`)
  }
  return `-- GENERATED by scripts/generate-holidays.ts (pnpm holidays:generate). Do not edit by hand.
-- Bolivian public holidays ${fromYear}-${toYear}, computed with the date-holidays library
-- (https://github.com/commenthol/date-holidays, code ISC, holiday data CC-BY-3.0).
-- To cover later years, generate another migration with --from/--to/--out.

insert into public.official_holidays (country_code, holiday_date, name) values
${rows.join(',\n')}
on conflict (country_code, holiday_date) do update set name = excluded.name;

insert into public.official_holiday_years (country_code, first_year, last_year)
values ('BO', ${fromYear}, ${toYear})
on conflict (country_code) do update set
  first_year = least(public.official_holiday_years.first_year, excluded.first_year),
  last_year = greatest(public.official_holiday_years.last_year, excluded.last_year);
`
}
