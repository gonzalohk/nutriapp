import { describe, expect, it } from 'vitest'
import { planMonth } from '@/domain/calendar'
import {
  earliestBrowsableMonth,
  endDateOnDeactivate,
  isAutoGeneratedMonth,
  startDateOnReactivate,
} from '@/domain/person-lifecycle'
import { toPlainDate } from '@/domain/plain-date'
import { computeStats } from '@/domain/stats'
import { COVERAGE, holidaySet } from './helpers/holidays'

const d = toPlainDate
const HOLIDAYS = holidaySet(2024, 2045)

describe('leaving and returning', () => {
  it('deactivating ends the plan yesterday so today\'s unrecorded meal is removed too', () => {
    expect(endDateOnDeactivate(d('2026-01-01'), null, d('2026-10-15'))).toBe('2026-10-14')
  })
  it('keeps an end date that was already set', () => {
    expect(endDateOnDeactivate(d('2026-01-01'), d('2026-09-30'), d('2026-10-15'))).toBe('2026-09-30')
  })
  it('never ends the plan before it started (added today, removed today)', () => {
    expect(endDateOnDeactivate(d('2026-10-15'), null, d('2026-10-15'))).toBe('2026-10-15')
  })
  it('reactivating someone who had left starts a new period today', () => {
    expect(startDateOnReactivate(d('2026-01-01'), d('2026-09-30'), d('2026-10-15'))).toBe('2026-10-15')
  })
  it('reactivating someone who was only hidden keeps the original start', () => {
    expect(startDateOnReactivate(d('2026-01-01'), null, d('2026-10-15'))).toBe('2026-01-01')
  })
  it('does not move a future start backwards', () => {
    expect(startDateOnReactivate(d('2026-11-01'), d('2026-11-30'), d('2026-10-15'))).toBe('2026-11-01')
  })
})

describe('month generation rules', () => {
  it('creates months automatically from the current month on, never earlier', () => {
    const today = d('2026-10-15')
    expect(isAutoGeneratedMonth(d('2026-10-01'), today)).toBe(true)
    expect(isAutoGeneratedMonth(d('2026-11-01'), today)).toBe(true)
    expect(isAutoGeneratedMonth(d('2026-09-01'), today)).toBe(false)
  })
  it('lets you browse back to the plan start or to the first month that exists, whichever is earlier', () => {
    expect(earliestBrowsableMonth(d('2026-08-12'), null)).toBe('2026-08-01')
    expect(earliestBrowsableMonth(d('2026-10-15'), d('2026-08-01'))).toBe('2026-08-01')
    expect(earliestBrowsableMonth(d('2026-08-12'), d('2026-09-01'))).toBe('2026-08-01')
  })
})

describe('several people', () => {
  const base = { month: d('2026-10-01'), deliveryWeekdays: [1, 2, 3, 4, 5] as const, planEnd: null, holidays: HOLIDAYS, exceptionalDates: new Set<never>(), holidayCoverage: COVERAGE }

  it('plans each person independently from their own terms and dates', () => {
    const ana = planMonth({ ...base, mealsPerMonth: 20, planStart: d('2026-01-01') })
    const beto = planMonth({ ...base, mealsPerMonth: 10, planStart: d('2026-01-01') })
    const carla = planMonth({ ...base, mealsPerMonth: 20, planStart: d('2026-10-15') })
    expect(ana.target).toHaveLength(20)
    expect(beto.target).toHaveLength(10)
    expect(carla.target[0]).toBe('2026-10-15')
    expect(carla.isPartial).toBe(true)
    expect(ana.isPartial).toBe(false)
  })

  it('keeps counters strictly per person', () => {
    const today = d('2026-10-15')
    const ana = computeStats({ meals: [{ date: d('2026-10-01'), status: 'picked_up', hasPhoto: true }], contracted: 20, isPartial: false, today })
    const beto = computeStats({ meals: [{ date: d('2026-10-01'), status: 'cancelled', hasPhoto: false }], contracted: 10, isPartial: false, today })
    expect([ana.pickedUp, ana.cancelled, ana.photos]).toEqual([1, 0, 1])
    expect([beto.pickedUp, beto.cancelled, beto.photos]).toEqual([0, 1, 0])
  })
})
