import { planMonth } from '@/domain/calendar'
import { isAutoGeneratedMonth } from '@/domain/person-lifecycle'
import { reconcileSummary, type ReconcileSummary } from '@/domain/reconcile'
import { compareDates, monthEnd, monthStart, toPlainDate, type PlainDate } from '@/domain/plain-date'
import { loadMonthInputs } from './calendar-data'
import { loadMonthMeals } from './history'
import type { Person } from './types'

export type DateChange = 'holiday-add' | 'holiday-remove' | 'exceptional-add'

export interface PreviewRow {
  person: Person
  month: PlainDate
  summary: ReconcileSummary
}

/**
 * What a holiday or exceptional-delivery change would do to each person's meals, computed before it
 * is saved so the user can confirm. Only people whose plan covers the date and months that exist (or
 * will be created automatically) are considered; rows with no effect are left out.
 */
export async function previewDateChange(
  people: readonly Person[],
  date: PlainDate,
  change: DateChange,
  today: PlainDate,
): Promise<PreviewRow[]> {
  const month = monthStart(date)
  const rows: PreviewRow[] = []

  for (const person of people.filter((p) => p.active)) {
    const start = toPlainDate(person.plan_start_date)
    if (compareDates(date, start) < 0) continue
    if (person.plan_end_date && compareDates(date, toPlainDate(person.plan_end_date)) > 0) continue

    const inputs = await loadMonthInputs(person, month)
    if (!inputs) continue
    const existing = await loadMonthMeals(person.id, month, monthEnd(month))
    if (existing.length === 0 && !isAutoGeneratedMonth(month, today)) continue

    const holidays = new Set(inputs.input.holidays)
    const exceptionalDates = new Set(inputs.input.exceptionalDates)
    if (change === 'holiday-add') holidays.add(date)
    if (change === 'holiday-remove') holidays.delete(date)
    if (change === 'exceptional-add') exceptionalDates.add(date)

    const plan = planMonth({ ...inputs.input, holidays, exceptionalDates })
    const summary = reconcileSummary(existing.map((m) => ({ date: m.mealDate, status: m.status })), plan.target, plan.windowStart)
    if (summary.hasChanges) rows.push({ person, month, summary })
  }
  return rows
}
