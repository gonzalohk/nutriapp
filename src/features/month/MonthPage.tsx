import { useMemo, useState } from 'react'
import { useQuery, useQueryClient } from '@tanstack/react-query'
import { PersonFilter } from '@/components/PersonFilter'
import { EmptyState, ErrorState } from '@/components/EmptyState'
import { Spinner } from '@/components/Spinner'
import { ensureMonthQuery } from '@/data/ensure'
import { errorMessage } from '@/data/errors'
import { ensureMonthPlan } from '@/data/mutations'
import { useSelectedPerson } from '@/data/selected-person'
import { useEarliestPlanMonth, useMonthView, usePeople } from '@/data/queries'
import { todayInBolivia } from '@/domain/bolivia-time'
import { buildCalendarCells } from '@/domain/month-view'
import { earliestBrowsableMonth, isAutoGeneratedMonth } from '@/domain/person-lifecycle'
import { computeStats } from '@/domain/stats'
import { addMonths, compareDates, monthStart, toPlainDate, type PlainDate } from '@/domain/plain-date'
import { monthTitle } from '@/i18n/format'
import { t } from '@/i18n/t'
import { ExcessBanner, InconsistencyBanner, NeedsReviewBanner } from './Banners'
import { CalendarGrid } from './CalendarGrid'
import { CounterStrip } from './CounterStrip'
import { ExceptionalDeliverySheet } from './ExceptionalDeliverySheet'
import { ShortfallBanner } from './ShortfallBanner'

export function MonthPage() {
  const people = usePeople()
  const thisMonth = monthStart(todayInBolivia())
  const [personId, setPersonId] = useSelectedPerson()
  const queryClient = useQueryClient()
  const [generating, setGenerating] = useState(false)
  const [generateError, setGenerateError] = useState<string | null>(null)
  const [month, setMonth] = useState<PlainDate>(thisMonth)
  const [showExceptional, setShowExceptional] = useState(false)

  const active = useMemo(() => (people.data ?? []).filter((p) => p.active), [people.data])
  const person = active.find((p) => p.id === personId) ?? active[0]

  // Navigation is bounded from the person's first plan month to one month ahead, so browsing
  // never creates rows for distant months.
  const earliest = useEarliestPlanMonth(person?.id)
  const firstMonth = person ? earliestBrowsableMonth(toPlainDate(person.plan_start_date), earliest.data ?? null) : thisMonth
  const lastMonth = addMonths(thisMonth, 1)
  const canGoBack = compareDates(month, firstMonth) > 0
  const canGoForward = compareDates(month, lastMonth) < 0

  // The current and next month are created automatically; earlier ones only on request, so
  // browsing never invents meals (for example in the gap of someone who left and came back).
  const auto = isAutoGeneratedMonth(month, thisMonth)
  const ensure = useQuery({
    ...(person ? ensureMonthQuery(person, month) : { queryKey: ['ensure', 'none'], queryFn: () => null }),
    enabled: Boolean(person) && auto,
  })
  const view = useMonthView(person, month, !auto || ensure.isSuccess)
  const ready = view.isSuccess && (!auto || ensure.isSuccess)
  const canGenerate = ready && !auto && view.data?.monthlyPlan === null && (view.data.plan?.target.length ?? 0) > 0

  async function generate() {
    if (!person) return
    setGenerating(true)
    setGenerateError(null)
    try {
      await ensureMonthPlan(person, month)
      await queryClient.invalidateQueries({ queryKey: ['month'] })
    } catch (error) {
      setGenerateError(errorMessage(error))
    }
    setGenerating(false)
  }

  const cells = useMemo(
    () =>
      view.data
        ? buildCalendarCells({ month, meals: view.data.meals, holidays: view.data.holidays, extraDays: view.data.plan?.extra ?? [] })
        : [],
    [view.data, month],
  )

  const stats = useMemo(
    () =>
      view.data && view.data.plan
        ? computeStats({
            meals: view.data.meals.map((m) => ({ date: m.date, status: m.status, hasPhoto: m.hasPhoto })),
            contracted: view.data.plan.contracted,
            isPartial: view.data.plan.isPartial,
            today: todayInBolivia(),
          })
        : null,
    [view.data],
  )

  if (people.isPending) return <Spinner />
  if (people.isError) return <ErrorState message={errorMessage(people.error)} onRetry={() => void people.refetch()} />
  if (!person) return <EmptyState>{t('month.noPeople')}</EmptyState>

  const plan = view.data?.plan
  const showShortfall = plan && !plan.isPartial && plan.shortfall > 0

  return (
    <section className="flex flex-col gap-3 p-4">
      <h1 className="sr-only">{t('month.title')}</h1>
      <PersonFilter people={active} value={person.id} onChange={setPersonId} />

      <div className="flex items-center justify-between">
        <button className="min-h-12 min-w-12 text-2xl disabled:opacity-30" aria-label={t('month.previous')} disabled={!canGoBack} onClick={() => setMonth(addMonths(month, -1))}>
          ‹
        </button>
        <p className="text-lg font-bold">{monthTitle(month)}</p>
        <button className="min-h-12 min-w-12 text-2xl disabled:opacity-30" aria-label={t('month.next')} disabled={!canGoForward} onClick={() => setMonth(addMonths(month, 1))}>
          ›
        </button>
      </div>

      {canGenerate && (
        <div className="rounded-xl border border-slate-300 bg-white p-3">
          <p className="mb-2 text-slate-700">{t('month.generateHint')}</p>
          <button className="min-h-12 rounded-xl bg-brand px-4 font-semibold text-white disabled:opacity-50" disabled={generating} onClick={() => void generate()}>
            {t('month.generate')}
          </button>
          {generateError && <p role="alert" className="mt-2 text-sm text-red-800">{generateError}</p>}
        </div>
      )}
      {ready && !auto && view.data?.monthlyPlan === null && !canGenerate && (
        <p className="text-slate-600">{t('month.nothingToGenerate')}</p>
      )}

      {ensure.isError && <ErrorState message={`${t('month.ensureError')} ${errorMessage(ensure.error)}`} onRetry={() => void ensure.refetch()} />}
      {!ensure.isError && !ready && <Spinner />}

      {ready && stats && <CounterStrip stats={stats} />}
      {ready && stats?.warnings.map((w) => w.kind === 'inconsistent' ? <InconsistencyBanner key={w.kind} warning={w} /> : w.kind === 'excess' ? <ExcessBanner key={w.kind} warning={w} /> : null)}
      {ready && view.data?.monthlyPlan?.needs_review && <NeedsReviewBanner />}

      {ready && plan && showShortfall && (
        <ShortfallBanner available={plan.validDays.length} contracted={plan.contracted} onAddExceptional={() => setShowExceptional(true)} />
      )}
      {ready && (auto || view.data?.monthlyPlan) && <CalendarGrid cells={cells} />}

      <button className="min-h-12 self-start rounded-xl px-2 font-semibold text-brand underline" onClick={() => setShowExceptional(true)}>
        {t('month.addExceptional')}
      </button>
      {showExceptional && <ExceptionalDeliverySheet month={month} onClose={() => setShowExceptional(false)} />}
    </section>
  )
}
