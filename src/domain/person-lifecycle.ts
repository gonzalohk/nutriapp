import { addDays, compareDates, monthStart, type PlainDate } from './plain-date'

const later = (a: PlainDate, b: PlainDate) => (compareDates(a, b) >= 0 ? a : b)

/**
 * Plan end date when someone is deactivated: the day before, so today's still-scheduled meal is
 * removed too. An end date already set is kept, and the end is never before the start.
 */
export function endDateOnDeactivate(planStart: PlainDate, planEnd: PlainDate | null, today: PlainDate): PlainDate {
  return planEnd ?? later(planStart, addDays(today, -1))
}

/**
 * Plan start date when someone returns. A person who had left starts a new period today, so the gap
 * produces no meals (nor false "not picked up" ones); earlier records stay untouched. A person who
 * was only hidden (no end date) keeps their original start.
 */
export function startDateOnReactivate(planStart: PlainDate, planEnd: PlainDate | null, today: PlainDate): PlainDate {
  return planEnd === null ? planStart : later(planStart, today)
}

/** Only the current and the next month are created automatically; earlier ones need an explicit action. */
export function isAutoGeneratedMonth(month: PlainDate, today: PlainDate): boolean {
  return compareDates(month, monthStart(today)) >= 0
}

/** The earliest month the Month screen lets you open: the plan's first month or the first one that exists. */
export function earliestBrowsableMonth(planStart: PlainDate, earliestExistingPlan: PlainDate | null): PlainDate {
  const start = monthStart(planStart)
  return earliestExistingPlan && compareDates(earliestExistingPlan, start) < 0 ? earliestExistingPlan : start
}
